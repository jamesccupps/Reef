// build_plants3.mjs — THE LAKES' WEEDS AT THEIR START (generated data for src/w3/plants3.js): the water and the plants (no fish)
// grown for YEARS whole years from the bare seeding at a lake's opening date (SEASON.START_YF), and the beds then — each species'
// shoots and storage per bed cell, last year's standing stems — written for Plants3.seed(), which loads them where they fit the
// world's bed cells (their count and key) and reshapes them to another start date (jump). Re-run it whenever the plants'
// numbers, the bed or the water's columns change (the gate checks the start still matches and still holds for a year).
//   node tools/hotbrook/build_plants3.mjs [years]                → src/w3/plants3init.js (the 1/10 world)
//   HB_WORLD=true node tools/hotbrook/build_plants3.mjs [years]  → src/w3/true/plants3init.js (the true lakes)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url)), src = join(here, '..', '..', 'src');
const { Env3 } = await import('../../src/w3/env3.js');
const { FORMS3, NF3, encodeQ } = await import('../../src/w3/plants3.js');
const { WORLD_TRUE } = await import('../../src/w3/geometry.js');
const { SEASON } = await import('../../src/config.js');
const { seed } = await import('../../src/core.js');
const { CLOCK3 } = await import('../../src/w3/clock3.js');
const YEARS = +(process.argv[2] || 5), B = 1752, YF = SEASON.START_YF;
seed(611);
const env = new Env3({ yf0: YF, plantInit: false }), P = env.plants;
const t0 = Date.now();
for (let y = 0; y < YEARS; y++) {
  let left = CLOCK3.YEAR_LEN; while (left > 1e-6) { const s = Math.min(B, left); env.step(s); left -= s; }   // (a whole year: back to YF)
  const tot = FORMS3.map((F, f) => [F.key, P.total(f) / 1000]).sort((a, b) => b[1] - a[1]).slice(0, 6).map(([k, v]) => `${k} ${v.toFixed(0)}`).join(' ');
  console.log(`year ${y + 1} (${((Date.now() - t0) / 1000).toFixed(0)} s): yf ${env.yearFrac().toFixed(3)} · kg DW of shoots: ${tot}`);
}
// the state: per species its shoots then its storage (n each), then the standing stems — Uint16 log codes, little-endian, base64
const n = P.cells.length, q = new Uint16Array(n * (2 * NF3 + 1));
for (let f = 0; f < NF3; f++) for (let i = 0; i < n; i++) { q[(2 * f) * n + i] = encodeQ(P.Bs[f][i]); q[(2 * f + 1) * n + i] = encodeQ(P.Br[f][i]); }
for (let i = 0; i < n; i++) q[2 * NF3 * n + i] = encodeQ(P.dead[i]);
const b64 = Buffer.from(q.buffer).toString('base64');
const out = join(src, 'w3', WORLD_TRUE ? 'true' : '', 'plants3init.js');
writeFileSync(out, `// plants3init.js — GENERATED by tools/hotbrook/build_plants3.mjs (the sim's data: pure). The ${WORLD_TRUE ? 'true' : '1/10'} world's weeds at a
// lake's opening (yf ${YF}) after ${YEARS} years grown from the bare seeding (water and plants, no fish; weather seed 611): per species
// its shoots and storage per bed cell (g DW/m²), then last year's standing stems — Uint16 log codes (plants3.js PI3_LOG), base64.
export const PI3 = { yf: ${YF}, years: ${YEARS}, n: ${n}, key: ${P.cellKey()}, species: ${JSON.stringify(FORMS3.map(F => F.key))},
  q: '${b64}' };
`, { encoding: 'utf8' });
console.log(`wrote ${out} (${(b64.length / 1024).toFixed(0)} KB, ${n} bed cells, ${NF3} species)`);
